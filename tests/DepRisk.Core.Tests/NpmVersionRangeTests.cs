    // Specifiers node-semver does not accept as ranges: tags, URLs, git, file, workspace, malformed text.
    private static readonly string[] NotRanges =
    [
        "latest",
        "next",
        "beta",
        "github:user/repo",
        "git+https://github.com/a/b.git",
        "https://example.com/a.tgz",
        "file:../a",
        "workspace:*",
        "npm:foo@^1",
        "1.2.3.4",
        "1.2.3-",
        "01.2.3",
        "1.02.3",
        ">=",
        "^",
        "~",
        "1.2.x.3",
        "a.b.c",
        ">>1.2.3",
        "1.2.3 - ",
        "- 1.2.3",
        "1.2.3 -2.0.0",
        ">=1.2.3 - 2.0.0",
        "1.2.3-beta..1",
        "1.2.3-01",
        "1.2.3+",
        "1.2.3 + build"
    ];

    private static NuGetVersion V(string text) => Ecosystem.Npm.TryParseVersion(text, out NuGetVersion? v) ? v! : throw new InvalidOperationException(text);

    [Fact]
    public void Every_supported_range_agrees_with_node_semver_for_every_version()
    {
        List<string> disagreements = [];

        foreach ((string range, string[] satisfying) in Cases)
        {
            Assert.True(NpmVersionRange.TryParse(range, out NpmVersionRange? parsed), $"range '{range}' should parse");

            foreach (string version in Versions)
            {
                bool expected = satisfying.Contains(version);
                bool actual = parsed!.Contains(V(version));

                if (expected != actual)
                {
                    disagreements.Add($"'{range}' vs {version}: node-semver {expected}, DepRisk {actual}");
                }
            }
        }

        Assert.Empty(disagreements);
    }

    [Fact]
    public void The_matrix_is_large_enough_to_mean_something()
    {
        Assert.True(Cases.Length >= 100);
        Assert.True(Versions.Length >= 35);
        Assert.True(Cases.Any(c => c.Satisfying.Length == 0), "some range matches nothing");
        Assert.True(Cases.Any(c => c.Satisfying.Length > 5), "some range matches many");
    }

    [Fact]
    public void Things_that_are_not_ranges_are_not_understood()
    {
        foreach (string text in NotRanges)
        {
            Assert.False(NpmVersionRange.TryParse(text, out NpmVersionRange? range), $"'{text}' must not parse");
            Assert.Null(range);
        }
    }

    [Fact]
    public void Null_and_oversized_text_are_not_understood()
    {
        Assert.False(NpmVersionRange.TryParse(null, out _));
        Assert.False(NpmVersionRange.TryParse(new string('1', 1001), out _));
        Assert.False(NpmVersionRange.TryParse("99999999999.0.0", out _));
    }

    [Fact]
    public void An_alias_specifier_uses_the_range_after_the_last_at_sign()
    {
        Assert.True(NpmVersionRange.TryParseSpec("npm:strip-ansi@^6.0.1", out NpmVersionRange? alias));
        Assert.True(alias!.Contains(V("6.0.1")));
        Assert.True(alias.Contains(V("6.9.0")));
        Assert.False(alias.Contains(V("7.0.0")));

        Assert.True(NpmVersionRange.TryParseSpec("npm:@scope/pkg@~1.2.0", out NpmVersionRange? scoped));
        Assert.True(scoped!.Contains(V("1.2.5")));
        Assert.False(scoped.Contains(V("1.3.0")));
    }

    [Theory]
    [InlineData("npm:strip-ansi")]
    [InlineData("npm:@scope/pkg")]
    [InlineData("npm:pkg@latest")]
    [InlineData("npm:")]
    public void An_alias_without_a_version_range_is_not_understood(string spec)
    {
        Assert.False(NpmVersionRange.TryParseSpec(spec, out _));
    }

    [Fact]
    public void A_plain_range_is_a_valid_specifier_too()
    {
        Assert.True(NpmVersionRange.TryParseSpec("^1.2.3", out NpmVersionRange? range));
        Assert.True(range!.Contains(V("1.9.0")));
        Assert.False(NpmVersionRange.TryParseSpec("latest", out _));
        Assert.False(NpmVersionRange.TryParseSpec(null, out _));
    }

    [Fact]
    public void Prerelease_versions_are_only_allowed_by_a_comparator_on_the_same_version()
    {
        Assert.True(NpmVersionRange.TryParse("^1.2.3-beta.2", out NpmVersionRange? range));

        Assert.True(range!.Contains(V("1.2.3-beta.4")));
        Assert.False(range.Contains(V("1.3.0-beta.1")));   // a prerelease of another version is excluded
        Assert.True(range.Contains(V("1.4.0")));
        Assert.False(range.Contains(V("2.0.0-alpha")));    // the generated upper bound is 2.0.0-0
    }
